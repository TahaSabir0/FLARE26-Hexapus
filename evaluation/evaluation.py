def find_json_files(base_path):
    """Recursively find all JSON files in the specified directory."""
    json_files = []
    for root, dirs, files in os.walk(base_path):
        for file in files:
            if file.endswith(".json"):
                json_files.append(os.path.join(root, file))
    return json_files


def load_and_merge_json_files(json_files):
    """Load and merge multiple JSON files into a single list.

    Each record is tagged with `_dataset` = the directory that holds its JSON file. The
    FLARE layout is `<split>/<Modality>/<dataset>/*.json`, so this lets us score
    PER-DATASET (the way the challenge ranks, ChallengeR) and not only pooled-per-task.
    Pooling datasets with different label spaces into one balanced accuracy is misleading
    (see the paper) — per-dataset macro is the headline, pooled is diagnostic.
    """
    all_data = []
    for json_file in json_files:
        try:
            dataset = os.path.basename(os.path.dirname(json_file))
            with open(json_file, "r") as f:
                data = json.load(f)
            records = data if isinstance(data, list) else [data]
            for rec in records:
                if isinstance(rec, dict):
                    rec.setdefault("_dataset", dataset)
            all_data.extend(records)
            print(f"Loaded {len(records)} samples from {os.path.basename(json_file)}")
        except Exception as e:
            print(f"Warning: Failed to load {json_file}: {e}")
    return all_data


def create_sample_key(sample):
    """Create a unique key for matching samples between ground truth and predictions."""
    image_name = str(sample.get("ImageName", sample.get("image", "")))
    question = str(sample.get("Question", ""))
    return f"{image_name}||{question}"


def validate_paths(ground_truth_path, prediction_file):
    """Validate that required paths exist."""
    # Check ground truth path
    if not os.path.exists(ground_truth_path):
        raise FileNotFoundError(
            f"Ground truth dataset directory not found: {ground_truth_path}"
        )

    # Find JSON files in ground truth path
    gt_files = find_json_files(ground_truth_path)
    if not gt_files:
        raise FileNotFoundError(f"No JSON files found in {ground_truth_path}")

    # Check prediction file
    if not os.path.exists(prediction_file):
        raise FileNotFoundError(f"Prediction file not found: {prediction_file}")

    return gt_files, True


