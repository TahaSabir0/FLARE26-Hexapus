def run_evaluation(args):
    """Main function to run evaluation comparing predictions with ground truth."""
    # Construct ground truth dataset path
    gt_dataset_path = os.path.join(args.base_dataset_path, "validation-public")

    # Validate paths
    print("Validating paths and discovering files...")
    gt_files, _ = validate_paths(gt_dataset_path, args.prediction_file)

    # Load ground truth data from validation-public directory
    print(f"Loading ground truth data from {gt_dataset_path}...")
    ground_truth_data = load_and_merge_json_files(gt_files)
    print(f"Total ground truth samples: {len(ground_truth_data)}")

    # Load prediction data
    print(f"Loading prediction data from {args.prediction_file}...")
    with open(args.prediction_file, "r") as f:
        prediction_data = json.load(f)
    print(f"Total prediction samples: {len(prediction_data)}")

    # Create lookup dictionaries
    gt_lookup = {create_sample_key(sample): sample for sample in ground_truth_data}
    pred_lookup = {create_sample_key(sample): sample for sample in prediction_data}

    # Debug: Print some sample matching info
    print(f"\nSample matching info:")
    print(f"GT lookup size: {len(gt_lookup)}")
    print(f"Pred lookup size: {len(pred_lookup)}")

    # Group data by task type (pooled) and by (task type, dataset) (per-dataset / ChallengeR)
    task_type_to_gt = {}
    task_type_to_pred = {}
    task_ds_to_gt = {}   # task_type -> dataset -> [gt answers]
    task_ds_to_pred = {}  # task_type -> dataset -> [pred answers]

    matched_samples = 0
    unmatched_samples = 0
    reportgen_pairs = []  # {gt, pred, sample_key} for the separate CRIMSON scorer (score_crimson.py)

    for sample_key, gt_sample in gt_lookup.items():
        task_type = gt_sample.get("TaskType", "").strip().lower()

        if not task_type:
            continue

        pred_sample = pred_lookup.get(sample_key)
        if pred_sample is None:
            unmatched_samples += 1
            continue

        gt_answer = gt_sample.get("Answer", "")
        pred_answer = pred_sample.get("Answer", "")
        dataset = gt_sample.get("_dataset", "unknown")

        task_type_to_gt.setdefault(task_type, []).append(gt_answer)
        task_type_to_pred.setdefault(task_type, []).append(pred_answer)
        task_ds_to_gt.setdefault(task_type, {}).setdefault(dataset, []).append(gt_answer)
        task_ds_to_pred.setdefault(task_type, {}).setdefault(dataset, []).append(pred_answer)
        if task_type == "report_generation":
            reportgen_pairs.append(
                {"sample_key": sample_key, "gt": gt_answer, "pred": pred_answer}
            )
        matched_samples += 1

    print(f"Successfully matched {matched_samples} samples for evaluation")
    print(f"Unmatched samples: {unmatched_samples}")

    # Calculate metrics for each task type
    print(f"\nCalculating metrics by task type...")
    evaluation_results = {}
    total_evaluated = 0

    for task_type in sorted(task_type_to_gt.keys()):
        gt_answers = task_type_to_gt[task_type]
        pred_answers = task_type_to_pred[task_type]

        metrics = calculate_task_metrics(pred_answers, gt_answers, task_type)
        metrics["num_examples"] = len(gt_answers)

        # The single metric this task reports (balanced_accuracy / detection_f1 / mean_absolute_error / ...)
        metric_key = next((k for k in metrics if k != "num_examples"), None)

        # PER-DATASET (ChallengeR) — score each dataset alone, then macro-average. This is the headline.
        # The pooled metric above stays as a diagnostic only. report_generation is skipped (GREEN reloads a
        # 7B model per call, and our report-gen is a single dataset, so pooled == per-dataset there).
        if task_type != "report_generation" and metric_key is not None:
            per_dataset = {}
            for ds in sorted(task_ds_to_gt.get(task_type, {})):
                ds_metrics = calculate_task_metrics(
                    task_ds_to_pred[task_type][ds], task_ds_to_gt[task_type][ds], task_type
                )
                ds_metrics["num_examples"] = len(task_ds_to_gt[task_type][ds])
                per_dataset[ds] = ds_metrics
            metrics["per_dataset"] = per_dataset
            macro_vals = [
                d[metric_key] for d in per_dataset.values()
                if d.get(metric_key) is not None and d[metric_key] != float("inf")
            ]
            if macro_vals:
                metrics[metric_key + "_macro"] = sum(macro_vals) / len(macro_vals)

        evaluation_results[task_type] = metrics
        total_evaluated += len(gt_answers)

        print(f"\n{task_type}:  samples: {len(gt_answers)}")
        macro_key = (metric_key + "_macro") if metric_key else None
        if macro_key and macro_key in metrics:
            print(f"  {macro_key} (HEADLINE, per-dataset macro): {metrics[macro_key]:.4f}")
        if metric_key is not None:
            pooled = metrics[metric_key]
            pooled_str = f"{pooled:.4f}" if isinstance(pooled, float) else f"{pooled}"
            print(f"  {metric_key} (pooled, diagnostic only): {pooled_str}")

    print(f"\nTotal evaluated samples: {total_evaluated}")

    # Save results
    print(f"\nSaving evaluation results...")
    os.makedirs(args.output_dir, exist_ok=True)
    output_file = os.path.join(args.output_dir, args.output_filename)

    with open(output_file, "w") as f:
        json.dump(evaluation_results, f, indent=2)

    print(f"Evaluation metrics saved to: {output_file}")

    # Dump matched report-gen pairs so the separate CRIMSON scorer (run from the crimson-score env)
    # can fill in the official report_generation.crimson_score. See REPORTGEN_SCORING.md / run_eval.sh.
    if reportgen_pairs:
        rg_file = os.path.join(args.output_dir, "reportgen_pairs.jsonl")
        with open(rg_file, "w") as f:
            for pair in reportgen_pairs:
                f.write(json.dumps(pair) + "\n")
        print(f"Report-gen pairs ({len(reportgen_pairs)}) for CRIMSON saved to: {rg_file}")

    return evaluation_results


